import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import nodemailer from 'nodemailer';
import jwt from 'jsonwebtoken';
import { databaseFixture, postgrestFetch } from '../test-support/postgres.js';
import { connectDatabase, databaseReady, disconnectDatabase, checkDatabaseHealth } from './db.js';
import { app } from '../server.js';

test('API Supabase: cadastro, perfil, reset SMTP, revogação, privacidade e limites', async t => {
  const { db } = await databaseFixture();
  const nativeFetch = globalThis.fetch;
  const transport = postgrestFetch(db);
  t.mock.method(globalThis, 'fetch', (url, init) => String(url).startsWith('https://fixture.invalid') ? transport(url, init) : nativeFetch(url, init));
  const config = { backend: 'supabase', supabaseUrl: 'https://fixture.invalid', supabaseServiceRoleKey: 'fixture-service-key', jwtSecret: 'test-secret-for-fixture-only-1234567890', nodeEnv: 'test', smtp: { configured: true, host: 'smtp.fixture.invalid', port: 587, user: 'fixture', password: 'fixture', from: 'test@example.test' } };
  assert.equal(Boolean(databaseReady()), false);
  await connectDatabase(config);
  assert.equal(await checkDatabaseHealth(), true);
  app.locals.config = config;
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await disconnectDatabase(); await db.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (path, method = 'GET', body, cookie) => nativeFetch(base+path, { method, headers: { ...(body ? {'Content-Type':'application/json'} : {}), ...(cookie ? { Cookie: cookie } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}), redirect: 'manual' });
  const registration = { fullName:'Cliente Teste',email:'cliente@example.test',phone:'11999999999',birthDate:'1990-01-01',password:'SenhaOriginal123' };
  assert.equal((await call('/api/auth/register','POST',registration)).status,201);
  assert.equal((await call('/api/auth/register','POST',registration)).status,409);
  assert.equal((await call('/api/auth/login','POST',{email:registration.email,password:'errada'})).status,401);
  const login = async password => {
    const response = await call('/api/auth/login','POST',{email:registration.email,password});
    assert.equal(response.status,200);
    const cookie = response.headers.getSetCookie().find(c => /^lavemais_session=.+; Path=\//.test(c)).split(';')[0];
    return cookie;
  };
  const cookie = await login(registration.password);
  const rawToken = cookie.slice(cookie.indexOf('=') + 1);
  const parts = rawToken.split('.');
  parts[2] = (parts[2][0] === 'a' ? 'b' : 'a') + parts[2].slice(1);
  const claims = jwt.decode(rawToken);
  const invalidTokens = [parts.join('.'),
    jwt.sign({ sub: claims.sub }, config.jwtSecret, { algorithm: 'HS384', issuer: 'lavemais-api', audience: 'lavemais-client', expiresIn: '1h' }),
    jwt.sign({ sub: claims.sub }, config.jwtSecret, { issuer: 'other', audience: 'lavemais-client', expiresIn: '1h' }),
    jwt.sign({ sub: claims.sub }, config.jwtSecret, { issuer: 'lavemais-api', audience: 'other', expiresIn: '1h' }),
    jwt.sign({ sub: claims.sub }, config.jwtSecret, { issuer: 'lavemais-api', audience: 'lavemais-client', expiresIn: -1 })];
  for (const token of invalidTokens) {
    assert.equal((await call('/api/auth/me', 'GET', undefined, 'lavemais_session=' + token)).status, 401);
  }
  const profile = await call('/api/client/profile','GET',undefined,cookie);
  assert.equal(profile.status,200); assert.equal(profile.headers.get('cache-control'),'no-store');
  assert.equal('passwordHash' in (await profile.json()).user,false);
  assert.equal((await call('/api/client/profile','PATCH',{fullName:'Nome Atualizado'},cookie)).status,200);
  assert.equal((await call('/api/client/profile','PATCH',{email:'attacker@example.test'},cookie)).status,400);
  assert.equal((await call('/conta/planos','GET',undefined,cookie)).status,200);
  const request = { service: 'Lavagem de roupas', preferredDate: new Date(Date.now() + 86400000).toISOString().slice(0,10), notes: 'Consultar condições' };
  assert.equal((await call('/api/client/appointments')).status,401);
  assert.equal((await call('/api/client/appointments','POST',{ ...request, user_id: 'forged' },cookie)).status,400);
  const created = await call('/api/client/appointments','POST',request,cookie);
  assert.equal(created.status,201);
  const appointment = (await created.json()).appointment;
  assert.equal(appointment.status,'pending');
  assert.equal(appointment.revision,0);
  assert.equal('user_id' in appointment,false);
  const list = await call('/api/client/appointments?page=1&status=pending','GET',undefined,cookie);
  assert.equal(list.status,200);
  assert.equal((await list.json()).appointments[0].id,appointment.id);
  const other = (await db.query("insert into public.users(full_name,email,phone,birth_date,password_hash) values ('Outra Pessoa','outra@example.test','11999999999','1990-01-01','unused') returning id")).rows[0];
  const foreign = (await db.query("insert into public.appointment_requests(user_id,service,preferred_date) values ($1,'Privado',$2) returning id",[other.id,request.preferredDate])).rows[0];
  assert.equal((await call(`/api/client/appointments/${foreign.id}`,'PATCH',{...request,revision:0},cookie)).status,409);
  assert.equal((await call(`/api/client/appointments/${foreign.id}/cancel`,'POST',{revision:0},cookie)).status,409);
  assert.equal((await call('/api/client/dashboard')).status,401);
  const dashboardResponse = await call('/api/client/dashboard?userId='+other.id,'GET',undefined,cookie);
  assert.equal(dashboardResponse.status,200);
  const dashboard = await dashboardResponse.json();
  assert.equal(dashboard.upcomingCount,1);
  assert.equal(dashboard.next.id,appointment.id);
  assert.deepEqual(dashboard.recent.map(item=>item.id),[appointment.id]);
  assert.equal((await call('/conta/historico','GET',undefined,cookie)).status,200);
  const edited = await call(`/api/client/appointments/${appointment.id}`,'PATCH',{...request,notes:'Alterado',revision:0},cookie);
  assert.equal(edited.status,200);
  assert.equal((await edited.json()).appointment.revision,1);
  assert.equal((await call(`/api/client/appointments/${appointment.id}`,'PATCH',{...request,revision:0},cookie)).status,409);
  assert.equal((await call(`/api/client/appointments/${appointment.id}/cancel`,'POST',{revision:1},cookie)).status,200);
  assert.equal((await call(`/api/client/appointments/${appointment.id}`,'PATCH',{...request,revision:2},cookie)).status,409);
  const persisted = (await (await call('/api/client/appointments?status=cancelled','GET',undefined,cookie)).json()).appointments;
  assert.equal((await (await call('/api/client/dashboard','GET',undefined,cookie)).json()).upcomingCount,0);
  assert.equal(persisted.length,1); assert.equal(persisted[0].notes,'Alterado');
  assert.equal((await call('/api/client/appointments?page=-1','GET',undefined,cookie)).status,400);
  await db.query("insert into public.appointment_requests(user_id,service,preferred_date) select $1,'Histórico '||n,$2 from generate_series(1,21) n",[other.id,request.preferredDate]);
  assert.equal((await (await call('/api/client/appointments','GET',undefined,cookie)).json()).appointments.length,1,'foreign records never enter owner pagination');
  const owner = (await db.query('select id from public.users where email=$1',[registration.email])).rows[0];
  await db.query("insert into public.appointment_requests(user_id,service,preferred_date) select $1,'Atendimento '||n,$2 from generate_series(1,21) n",[owner.id,request.preferredDate]);
  const firstPage = await (await call('/api/client/appointments?status=pending','GET',undefined,cookie)).json();
  const secondPage = await (await call('/api/client/appointments?status=pending&page=2','GET',undefined,cookie)).json();
  assert.equal(firstPage.appointments.length,20); assert.equal(firstPage.hasMore,true);
  assert.equal(secondPage.appointments.length,1); assert.equal(secondPage.hasMore,false);
  assert.ok(!firstPage.appointments.some(row=>row.id===secondPage.appointments[0].id));
  assert.equal((await call('/api/staff/appointments','GET',undefined,cookie)).status,403,'ordinary clients cannot see the team queue');
  assert.equal((await call('/equipe','GET',undefined,cookie)).status,403);
  assert.equal((await call('/api/staff/appointments')).status,401);
  config.staffUserIds=[owner.id];
  const queue=await call('/api/staff/appointments','GET',undefined,cookie);
  assert.equal(queue.status,200);
  assert.equal((await queue.json()).appointments.length,20);
  assert.equal((await call('/equipe','GET',undefined,cookie)).status,200);
  const target=firstPage.appointments[0];
  const decision={revision:target.revision,status:'confirmed',message:'Atendimento confirmado para a data solicitada às 10h. Pagamento na unidade.'};
  assert.equal((await call('/api/staff/appointments/'+target.id,'PATCH',{...decision,status:'paid'},cookie)).status,400);
  assert.equal((await call('/api/staff/appointments/'+target.id,'PATCH',decision,cookie)).status,200);
  assert.equal((await call('/api/staff/appointments/'+target.id,'PATCH',decision,cookie)).status,409);
  assert.equal((await call('/api/client/appointments/'+target.id,'PATCH',{...request,revision:1},cookie)).status,409);
  const confirmed=await (await call('/api/client/appointments?status=confirmed','GET',undefined,cookie)).json();
  assert.equal(confirmed.appointments[0].staffMessage,decision.message);
  assert.equal('staff_history' in confirmed.appointments[0],false);
  const history=(await db.query('select staff_history from public.appointment_requests where id=$1',[target.id])).rows[0].staff_history;
  assert.equal(history.length,1);assert.equal(history[0].actor,owner.id);
  assert.equal((await nativeFetch(base+'/api/client/appointments',{method:'POST',headers:{'Content-Type':'application/json','Sec-Fetch-Site':'cross-site',Cookie:cookie},body:JSON.stringify(request)})).status,403);
  let code, fail = true;
  t.mock.method(nodemailer, 'createTransport', () => ({ sendMail: async message => {
    if (fail) throw new Error('SMTP fixture failure');
    code=message.text.match(/\d{6}/)[0];
    assert.match(message.html,/Nome Atualizado/);assert.ok(message.html.includes(code));
    assert.match(message.html,/recuperar-senha/);
  } }));
  assert.equal((await call('/api/auth/password-reset/request','POST',{email:registration.email})).status,503);
  assert.equal((await db.query('select password_reset_code_hash from public.users where email=$1',[registration.email])).rows[0].password_reset_code_hash,null);
  fail=false;
  assert.equal((await call('/api/auth/password-reset/request','POST',{email:registration.email})).status,200);
  assert.match(code,/^\d{6}$/);
  const reset = {email:registration.email,code,password:'NovaSenha123'};
  assert.equal((await call('/api/auth/password-reset/confirm','POST',reset)).status,200);
  assert.equal((await call('/api/auth/password-reset/confirm','POST',reset)).status,400);
  assert.equal((await call('/api/auth/me','GET',undefined,cookie)).status,401);
  const nextCookie=await login(reset.password);
  assert.equal((await call('/api/auth/logout','POST',undefined,nextCookie)).status,204);
  assert.equal((await call('/api/auth/me','GET',undefined,nextCookie)).status,401,'copied token is revoked');
  const thirdCookie=await login(reset.password);
  assert.notEqual(thirdCookie,nextCookie,'new login receives a unique token');
  assert.equal((await call('/api/auth/me','GET',undefined,thirdCookie)).status,200);
  assert.equal((await nativeFetch(base+'/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:'{broken'})).status,400);
  assert.equal((await call('/api/auth/login','POST',{padding:'a'.repeat(17000)})).status,413);
  let limited;
  for(let i=0;i<12;i++) { limited=await call('/api/auth/login','POST',{email:registration.email,password:'errada'}); if(limited.status===429) break; }
  assert.equal(limited.status,429);
  assert.ok(limited.headers.get('retry-after'));
});
